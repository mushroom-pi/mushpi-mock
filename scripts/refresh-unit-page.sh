#!/bin/sh
# refresh-unit-page.sh — re-vendor the on-unit page assets from the grow checkout.
#
# The mock serves a byte-identical copy of the firmware's unit page:
#   mushpi-grow/app/unit.html        -> src/mushpi_mock/static/unit.html
#   mushpi-grow/app/static/unit.js   -> src/mushpi_mock/static/unit.js
#   mushpi-grow/app/static/favicon.svg -> src/mushpi_mock/static/favicon.svg
#
# The mock-only differences (simulated labels + restart caveat) are NOT in these
# bytes — they are applied at render time in src/mushpi_mock/unit_page.py
# (MOCK_PAGE_EDITS), so the vendored files stay byte-identical and
# check-unit-page-drift.sh can compare them with a plain hash.
#
# Run this when the firmware page changes (grow bumps the page). It copies the
# three assets and regenerates the VENDOR manifest with fresh hashes, then
# reminds you to re-check the render-time anchors — a firmware reword makes
# unit_page.py fail loudly at import (by design), and this script tells you
# where to fix it.
#
# Read-only toward mushpi-grow; writes only inside mushpi-mock/src.
# Exit codes: 0 refreshed | 2 grow checkout or an asset not found.

set -u

SCRIPT_DIR=$(CDPATH='' cd "$(dirname "$0")" && pwd)
MOCK_ROOT=$(CDPATH='' cd "$SCRIPT_DIR/.." && pwd)
GROW_ROOT="$MOCK_ROOT/../mushpi-grow"
STATIC_DIR="$MOCK_ROOT/src/mushpi_mock/static"
VENDOR="$STATIC_DIR/VENDOR"
PREFIX='unit-page-refresh:'

hash_file() {
    if command -v sha256sum >/dev/null 2>&1; then
        sha256sum "$1" | awk '{print $1}'
    else
        python3 -c 'import hashlib,sys;print(hashlib.sha256(open(sys.argv[1],"rb").read()).hexdigest())' "$1"
    fi
}

[ -d "$GROW_ROOT/app/static" ] || {
    echo "$PREFIX ERROR: grow checkout not found at $GROW_ROOT" >&2
    exit 2
}

# asset name -> grow source path (closed set — the spec's /static enum plus the host page)
for pair in \
    "unit.html:app/unit.html" \
    "unit.js:app/static/unit.js" \
    "favicon.svg:app/static/favicon.svg"
do
    name=${pair%%:*}
    src=${pair#*:}
    [ -f "$GROW_ROOT/$src" ] || {
        echo "$PREFIX ERROR: $GROW_ROOT/$src missing (page assets moved?)" >&2
        exit 2
    }
    cp "$GROW_ROOT/$src" "$STATIC_DIR/$name"
    echo "$PREFIX copied $GROW_ROOT/$src -> src/mushpi_mock/static/$name"
done

# Regenerate the VENDOR manifest (recorded hashes the drift check compares against).
GROW_COMMIT=$(git -C "$GROW_ROOT" rev-parse --short HEAD 2>/dev/null || echo unknown)
GROW_BRANCH=$(git -C "$GROW_ROOT" rev-parse --abbrev-ref HEAD 2>/dev/null || echo unknown)
REMOTE_HEAD=$(git -C "$GROW_ROOT" rev-parse --short origin/dev 2>/dev/null || echo unknown)

{
    echo "# mushpi-mock vendored on-unit page — provenance manifest"
    echo "# Byte-identical copies of the firmware's unit page assets."
    echo "# Mock-only differences (simulated labels, restart caveat) are applied at"
    echo "# render time in src/mushpi_mock/unit_page.py — do NOT edit the assets here."
    echo "# Regenerated by scripts/refresh-unit-page.sh; read by scripts/check-unit-page-drift.sh."
    echo "source_repo mushpi-grow"
    echo "source_branch $GROW_BRANCH"
    echo "source_commit $GROW_COMMIT"
    echo "remote_dev_head $REMOTE_HEAD"
    echo "asset unit.html $(hash_file "$STATIC_DIR/unit.html") source app/unit.html"
    echo "asset unit.js $(hash_file "$STATIC_DIR/unit.js") source app/static/unit.js"
    echo "asset favicon.svg $(hash_file "$STATIC_DIR/favicon.svg") source app/static/favicon.svg"
} > "$VENDOR"

echo "$PREFIX wrote $VENDOR (grow $GROW_BRANCH @ $GROW_COMMIT, origin/dev head $REMOTE_HEAD)"
echo "$PREFIX NEXT: review the MOCK_PAGE_EDITS anchors in src/mushpi_mock/unit_page.py —"
echo "$PREFIX       if the firmware reworded a labelled sentence the page import now"
echo "$PREFIX       raises; re-point the anchor to the new wording (labels stay)."

exit 0
